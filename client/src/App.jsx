import { useCallback, useEffect, useMemo, useState } from 'react';
import React from 'react';
const API = (import.meta.env.VITE_API_URL || 'http://localhost:4000').replace(/\/$/, '');
const fallbackUsers = [
  { id: 'user-asha', name: 'Asha Fernando', avatar: 'AF' },
  { id: 'user-nimal', name: 'Nimal Perera', avatar: 'NP' },
];
const money = value => `Rs. ${new Intl.NumberFormat('en-LK', { maximumFractionDigits: 0 }).format(value)}`;

async function request(path, options) {
  const response = await fetch(`${API}${path}`, options);
  let result;
  try { result = await response.json(); } catch { throw new Error('Server returned an invalid response.'); }
  if (!response.ok) throw new Error(result.error || 'Request failed.');
  return result;
}

function ListingCard({ listing, onAction, busy }) {
  const isProperty = listing.category === 'property';
  const label = isProperty ? `${listing.propertyType} · ${listing.bedrooms} bed · ${listing.bathrooms} bath`
    : `${listing.make} ${listing.model} · ${listing.year}`;
  return (
    <article className={`listing-card ${listing.alreadyInteracted ? 'previously-seen' : ''}`}>
      <div className={`card-image ${isProperty ? 'property-bg' : 'vehicle-bg'}`}>
        {listing.imageKey
          ? <img src={`${API}/api/listings/${listing.id}/image`} alt={`${listing.title} fictional sample illustration`} loading="lazy" />
          : <div className="image-placeholder" aria-hidden="true">{isProperty ? '⌂' : '◈'}</div>}
        <span className="category-chip">{isProperty ? '⌂ Property' : '◈ Vehicle'}</span>
        {listing.alreadyInteracted && <span className="history-chip">Previously explored</span>}
      </div>
      <div className="card-content">
        <div className="card-location">⌖ {listing.location}, Sri Lanka</div>
        <h3>{listing.title}</h3>
        <p className="detail-line">{label}</p>
        <div className="price">{money(listing.price)}</div>
        <div className="why" title="Explanation generated by the backend ranking algorithm">
          <span className="sparkle">✦</span>
          <span>{listing.reasons.join(' · ')}</span>
        </div>
        <div className="actions">
          <button type="button" disabled={busy || listing.interactionTypes.includes('view')} onClick={() => onAction(listing.id, 'view')}>
            {listing.interactionTypes.includes('view') ? '✓ Viewed' : '◉ View'}
          </button>
          <button type="button" disabled={busy || listing.interactionTypes.includes('save')} onClick={() => onAction(listing.id, 'save')}>
            {listing.interactionTypes.includes('save') ? '✓ Saved' : '♡ Save'}
          </button>
          <button className="contact" type="button" disabled={busy || listing.interactionTypes.includes('contact')} onClick={() => onAction(listing.id, 'contact')}>
            {listing.interactionTypes.includes('contact') ? '✓ Contacted' : '✉ Contact'}
          </button>
        </div>
      </div>
    </article>
  );
}

export default function App() {
  const [users, setUsers] = useState(fallbackUsers);
  const [userId, setUserId] = useState(() => {
    try { return localStorage.getItem('primefeed-selected-user') || 'user-asha'; } catch { return 'user-asha'; }
  });
  const [feed, setFeed] = useState(null);
  const [filter, setFilter] = useState('all');
  const [revision, setRevision] = useState(0);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const user = users.find(item => item.id === userId) || users[0];

  useEffect(() => {
    request('/api/users').then(result => setUsers(result.users)).catch(() => {});
  }, []);

  useEffect(() => {
    try { localStorage.setItem('primefeed-selected-user', userId); } catch { /* storage unavailable */ }
    let active = true;
    setLoading(true);
    setError('');
    request(`/api/feed?userId=${encodeURIComponent(userId)}`)
      .then(data => { if (active) setFeed(data); })
      .catch(err => { if (active) { setFeed(null); setError(err.message); } })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [userId, revision]);

  const onAction = useCallback(async (listingId, type) => {
    setBusy(true);
    setError('');
    try {
      await request('/api/interactions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ userId, listingId, type }),
      });
      setRevision(n => n + 1); // fetch freshly ranked results from MongoDB
    } catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }, [userId]);

  const shown = useMemo(() => (feed?.listings || []).filter(listing => filter === 'all' || listing.category === filter), [feed, filter]);
  const pickedCount = (feed?.listings || []).filter(item => item.alreadyInteracted).length;

  return (
    <div className="app-shell">
      <header className="navbar">
        <div className="brand"><span className="brand-symbol">P<span>.</span></span><span>Prime<span className="brand-light">Feed</span></span></div>
        <div className="nav-right"><span className="demo-pill">INTERACTIVE DEMO</span><span className="nav-separator" /><span className="top-caption">PrimeMarket.lk assessment</span></div>
      </header>
      <main className="layout">
        <section className="welcome-bar">
          <div>
            <p className="eyebrow">DISCOVER YOUR NEXT MOVE</p>
            <h1>Made for your <em>next chapter.</em></h1>
            <p className="hero-sub">A property and vehicle marketplace that learns what matters to you.</p>
          </div>
          <div className="user-switch">
            <label htmlFor="user-select">YOU'RE BROWSING AS</label>
            <div className="selector-row"><span className="avatar">{user?.avatar}</span>
              <select id="user-select" aria-label="Select demo user" value={userId} onChange={e => { setUserId(e.target.value); setFilter('all'); }}>
                {users.map(item => <option key={item.id} value={item.id}>{item.name}</option>)}
              </select>
            </div>
            <small>Switch users to see separate recommendations</small>
          </div>
        </section>

        <div className="workspace">
          <section className="feed-area" aria-label="Personalized listing feed">
            <div className="feed-head">
              <div>
                <div className="section-kicker">YOUR MARKETPLACE</div>
                <h2>{feed?.personalized ? 'Recommended for you' : 'Explore our listings'} <span className="count">{shown.length}</span></h2>
                <p>{feed?.personalized ? 'Ranked using your saved preferences and browsing activity.' : 'Discover something great. Your interactions will personalize this feed.'}</p>
              </div>
              <button type="button" className="refresh" onClick={() => setRevision(x => x + 1)} disabled={loading}>↻ Refresh feed</button>
            </div>
            <div className="filters" role="group" aria-label="Category filter">
              {[
                ['all', 'All listings'], ['property', 'Properties'], ['vehicle', 'Vehicles']
              ].map(([value, text]) => <button type="button" key={value} className={filter === value ? 'active' : ''} onClick={() => setFilter(value)}>{text}</button>)}
              <span className="sort-note">✦ Ranked for {user?.name.split(' ')[0]}</span>
            </div>
            {error && <div className="error" role="alert">{error} Check that MongoDB is running and you ran the seed script.</div>}
            {loading ? <div className="loading">Loading your personalized feed…</div>
              : <div className="cards">{shown.map(listing => <ListingCard key={listing.id} listing={listing} onAction={onAction} busy={busy} />)}</div>}
            {!loading && !shown.length && !error && <div className="loading">No listings in this category.</div>}
          </section>
          <aside className="sidebar">
            <div className="sidebar-box">
              <div className="box-icon">✧</div>
              <h3>Your feed, your way.</h3>
              <p>Every interaction helps us understand your interests. Come back later and your picks will still be here.</p>
              <div className="line" />
              <div className="stat"><span>Current user</span><strong>{user?.name}</strong></div>
              <div className="stat"><span>Feed mode</span><strong>{feed?.personalized ? 'Personalized' : 'Discovery'}</strong></div>
              <div className="stat"><span>Items explored</span><strong>{pickedCount}</strong></div>
            </div>
            <div className="sidebar-box help-box">
              <h3>How recommendations work</h3>
              <div className="weight-row"><span>◉ View listing</span><strong>+1</strong></div>
              <div className="weight-row"><span>♡ Save listing</span><strong>+4</strong></div>
              <div className="weight-row"><span>✉ Contact seller</span><strong>+6</strong></div>
              <p>Matching category, city, make or property type helps fresh listings move up. Repeated clicks count once.</p>
            </div>
            <div className="sidebar-foot">Made with React, Express, MongoDB &amp; private AWS S3</div>
          </aside>
        </div>
      </main>
      <footer>PrimeFeed · Fictional sample listings for a technical assessment · Contact action records interest only</footer>
    </div>
  );
}
